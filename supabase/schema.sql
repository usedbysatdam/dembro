create or replace function public.set_plan(new_plan text)
returns void
language plpgsql
security definer
set search_path = public
as $$
begin
  if new_plan not in ('free', 'premium') then
    raise exception 'Invalid plan';
  end if;
  if auth.uid() is null then
    raise exception 'Not authenticated';
  end if;
  update public.profiles
     set plan = new_plan,
         plan_renews_at = case when new_plan = 'premium' then now() + interval '1 year' else null end
   where id = auth.uid();
end;
$$;

revoke all on function public.set_plan(text) from public;
grant execute on function public.set_plan(text) to authenticated;

