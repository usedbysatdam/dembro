-- Public author card for the feed
-- profiles RLS keeps rows owner-only, so the feed reads names and
-- handles through this view. It exposes no email, plan, or grade.
-- ------------------------------------------------------------

create or replace view public.community_authors as
  select
    p.id,
    coalesce(nullif(p.full_name, ''), p.handle, 'Anggota Educrazy') as display_name,
    p.handle,
    p.role
  from public.profiles p;

grant select on public.community_authors to authenticated;
revoke all on public.community_authors from anon;

