create table if not exists public.profiles (
  id uuid primary key references auth.users (id) on delete cascade,
  full_name text,
  handle text unique,
  role text check (role in ('parent', 'teacher', 'homeschool')) default 'parent',
  grade_focus text,
  plan text check (plan in ('free', 'premium')) default 'free',
  plan_renews_at timestamptz,
  created_at timestamptz not null default now()
);

-- Existing installs: add the community handle without recreating the table.
alter table public.profiles add column if not exists handle text;
create unique index if not exists profiles_handle_key on public.profiles (lower(handle));

create table if not exists public.resources (
  id bigint primary key generated by default as identity,
  slug text unique not null,
  title text not null,
  description text,
  type text not null check (type in ('worksheet', 'game', 'lesson_plan', 'activity')),
  grade text not null,
  subject text not null,
  standards text,
  is_premium boolean not null default false,
  accent text not null default '#2fae5e',
  downloads integer not null default 0,
  duration text,
  created_at timestamptz not null default now()
);

create table if not exists public.collections (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references auth.users (id) on delete cascade,
  name text not null,
  created_at timestamptz not null default now()
