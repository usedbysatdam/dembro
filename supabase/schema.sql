-- ------------------------------------------------------------
-- Auto-create a profile after signup
-- ------------------------------------------------------------

create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  base_handle text;
  final_handle text;
  suffix integer := 0;
begin
  -- Community handle: slugify the name (or email local part), then de-duplicate.
  base_handle := regexp_replace(
    lower(coalesce(nullif(new.raw_user_meta_data ->> 'full_name', ''), split_part(new.email, '@', 1))),
    '[^a-z0-9]', '', 'g'
  );
  if base_handle is null or base_handle = '' then
    base_handle := 'edumember';
  end if;
  base_handle := left(base_handle, 18);
  final_handle := base_handle;
  while exists (select 1 from public.profiles p where lower(p.handle) = final_handle) loop
    suffix := suffix + 1;
    final_handle := base_handle || suffix::text;
  end loop;

  insert into public.profiles (id, full_name, handle, role, grade_focus)
  values (
    new.id,
    coalesce(new.raw_user_meta_data ->> 'full_name', ''),
    final_handle,
    -- Only allow roles the check constraint accepts; anything else falls back to parent.
    case when new.raw_user_meta_data ->> 'role' in ('parent', 'teacher', 'homeschool')
         then new.raw_user_meta_data ->> 'role' else 'parent' end,
    new.raw_user_meta_data ->> 'grade_focus'
  )
  on conflict (id) do nothing;
  return new;
end;
$$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
  after insert on auth.users
  for each row execute function public.handle_new_user();

